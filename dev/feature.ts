// Play Store feature graphic (1024x500): floor 2 on the right, logo on the left.
import * as THREE from 'three';
import { parseFloor, heightAt } from '../src/levels.ts';
import { FloorView, makeLineUniforms } from '../src/floor.ts';
import { IsoCamera } from '../src/camera.ts';
import { BallView } from '../src/ball.ts';
import { Footballer } from '../src/player.ts';
import { TargetView } from '../src/target.ts';
import { makeSkyFade, makeOutlineUniforms } from '../src/toon.ts';
import { BALL_R } from '../src/physics.ts';

await document.fonts.load("700 92px 'Fredoka'");
const W = 1024, H = 500;
const canvas = document.getElementById('c') as HTMLCanvasElement;
const renderer = new THREE.WebGLRenderer({ canvas, antialias: true, preserveDrawingBuffer: true });
renderer.setPixelRatio(1);
renderer.setSize(W, H, false);
const floor = parseFloor(0);
const sky = new THREE.Color(floor.sky);
document.body.style.background = floor.sky;
const scene = new THREE.Scene();
scene.background = sky;
scene.add(new THREE.HemisphereLight(0xffffff, 0x9cc864, 1.85));
const sun = new THREE.DirectionalLight(0xffffff, 1.55);
sun.position.set(-2, 5, 3);
scene.add(sun);
const lineU = makeLineUniforms();
lineU.uResolution.value.set(W, H);
const view = new FloorView(floor, sky, lineU, 1024, 8);
scene.add(view.group);
const target = new TargetView();
target.setRadius(floor.def.radius);
const [tx, tz] = floor.def.target;
target.group.position.set(tx, heightAt(floor, tx, tz) + 0.004, tz);
target.setDecor(false);
target.update(0.2);
scene.add(target.group);
const fade = makeSkyFade(sky);
fade.uFadeTop.value = floor.minTop - 0.35; fade.uFadeBottom.value = floor.minTop - 3.9;
const outU = makeOutlineUniforms();
const ball = new BallView(fade, outU);
const bx = 2.35, bz = 3.55;
const gy = heightAt(floor, bx, bz);
ball.group.position.set(bx, gy + BALL_R, bz);
ball.shadow.set(bx, gy, bz, 0);
scene.add(ball.group, ball.shadow.mesh);
const p = new Footballer(fade, outU);
const dx = 1.5 - bx, dz = 2.0 - bz; const L = Math.hypot(dx, dz);
const th = Math.atan2(dx / L, dz / L);
const px = bx - dx / L * 0.3 - Math.cos(th) * 0.25, pz = bz - dz / L * 0.3 + Math.sin(th) * 0.25;
p.root.position.set(px, heightAt(floor, px, pz), pz);
p.faceDir(dx, dz, true);
p.setPose('aim'); p.setWindup(0.7);
for (let k = 0; k < 30; k++) p.update(1 / 60);
p.shadow.set(px, heightAt(floor, px, pz), pz, 0);
scene.add(p.root, p.shadow.mesh);
const cam = new IsoCamera();
const pts: THREE.Vector3[] = [];
for (const t of floor.tiles) for (const [ax, az, k] of [[0,0,0],[1,0,1],[1,1,2],[0,1,3]] as const) {
  pts.push(new THREE.Vector3(t.i + ax, t.c[k], t.j + az), new THREE.Vector3(t.i + ax, t.c[k] + 0.8, t.j + az), new THREE.Vector3(t.i + ax, floor.minTop - 0.4, t.j + az));
}
cam.frame(pts, W, H, { top: 26, bottom: -330, left: 470, right: 0 }, true, 1000);
cam.update(0);
const css = Math.max(1.2, cam.scale * 0.02);
lineU.uLineWidth.value = css;
outU.uOutline.value = (css * 0.95) / cam.scale;
renderer.render(scene, cam.cam);
(window as any).__ready = true;
