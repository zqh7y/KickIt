import * as THREE from 'three';
import { parseFloor, heightAt } from '../src/levels.ts';
import { FloorView, makeLineUniforms } from '../src/floor.ts';
import { IsoCamera } from '../src/camera.ts';
import { BallView } from '../src/ball.ts';
import { Footballer } from '../src/player.ts';
import { makeSkyFade, makeOutlineUniforms } from '../src/toon.ts';
import { BALL_R } from '../src/physics.ts';

const params = new URLSearchParams(location.search);
const idx = Number(params.get('floor') ?? 0);
const zoom = params.get('zoom');
const canvas = document.getElementById('c') as HTMLCanvasElement;
const renderer = new THREE.WebGLRenderer({ canvas, antialias: true });
const dpr = Math.min(devicePixelRatio, 2);
renderer.setPixelRatio(dpr);
const w = innerWidth, h = innerHeight;
renderer.setSize(w, h, false);
const floor = parseFloor(idx);
const sky = new THREE.Color(floor.sky);
const scene = new THREE.Scene();
scene.background = sky;
scene.add(new THREE.HemisphereLight(0xffffff, 0x8fbf5a, 1.9));
const sun = new THREE.DirectionalLight(0xffffff, 1.6);
sun.position.set(-2, 5, 3);
scene.add(sun);
const lineU = makeLineUniforms();
lineU.uResolution.value.set(w * dpr, h * dpr);
const view = new FloorView(floor, sky, lineU, 1024, renderer.capabilities.getMaxAnisotropy());
scene.add(view.group);
const fade = makeSkyFade(sky);
fade.uFadeTop.value = floor.minTop - 0.35; fade.uFadeBottom.value = floor.minTop - 3.9;
const outU = makeOutlineUniforms();
const ball = new BallView(fade, outU);
const [sx, sz] = floor.def.start;
const gy = heightAt(floor, sx, sz);
ball.group.position.set(sx, gy + BALL_R, sz);
scene.add(ball.group, ball.shadow.mesh);
ball.shadow.set(sx, gy, sz, 0);
const p = new Footballer(fade, outU);
const [tx, tz] = floor.def.target;
const dx = tx - sx, dz = tz - sz; const L = Math.hypot(dx, dz);
const px = sx - dx / L * 0.32, pz = sz - dz / L * 0.32;
p.root.position.set(px, heightAt(floor, px, pz), pz);
p.faceDir(dx, dz, true);
if (params.get('face')) p.faceDir(1, 1, true);
p.setPose((params.get('pose') as any) ?? 'idle');
p.update(0.016);
scene.add(p.root, p.shadow.mesh);
p.shadow.set(px, heightAt(floor, px, pz), pz, 0);
const cam = new IsoCamera();
const pts: THREE.Vector3[] = [];
if (zoom) {
  pts.push(new THREE.Vector3(sx - 0.8, gy, sz - 0.8), new THREE.Vector3(sx + 0.8, gy + 1, sz + 0.8));
} else for (const t of floor.tiles) for (const [ddx, ddz, k] of [[0,0,0],[1,0,1],[1,1,2],[0,1,3]] as const) {
  pts.push(new THREE.Vector3(t.i + ddx, t.c[k], t.j + ddz));
  pts.push(new THREE.Vector3(t.i + ddx, t.c[k] + 0.9, t.j + ddz));
}
cam.frame(pts, w, h, { top: 90, bottom: 60, left: 16, right: 16 }, true, zoom ? 1000 : 150);
cam.update(0);
lineU.uLineWidth.value = Math.max(1.5, cam.scale * 0.021 * dpr);
outU.uOutline.value = (cam.scale * 0.021) / cam.scale * 0.9;
renderer.render(scene, cam.cam);
(window as any).__dbg = { ball, scene, THREE }; (window as any).__ready = true;
